/**
 * Builds the three stylesheets this package ships from its three sources.
 *
 *   src/base.css    theme-independent tokens (space, radii, borders, type)
 *   src/density.css compact and spacious `--space-*` values
 *   src/light.css   light colour values: ramps, then semantic tokens
 *   src/dark.css    dark colour values: only the ones that differ from light
 *
 *   dist/index.css  both themes. Each themed colour is one `light-dark()`
 *                   declaration, and `color-scheme` picks the branch: the OS
 *                   setting by default, `data-theme` on `<html>` to force one.
 *   dist/light.css  light only, for an app that ships one theme
 *   dist/dark.css   dark only, light values overlaid with `src/dark.css`
 *
 * WHY `light-dark()` AND NOT A DARK BLOCK
 *
 * The stylesheet this package replaced wrote the dark values twice: once inside
 * `@media (prefers-color-scheme: dark)` and once under `[data-theme="dark"]`,
 * because CSS cannot share one declaration block between a media query and a
 * selector. The two copies had to be kept in step by hand. With `light-dark()`
 * each token is declared once, and the switch is a single `color-scheme`
 * property, so there is nothing to keep in step.
 *
 * The sources stay as separate light and dark files because that is how a
 * person reads and reviews a palette, and because the contrast check in
 * `apps/docs` measures them directly. The dark file is an overlay, so a token
 * that exists only in `dark.css` has no light value to pair with and fails the
 * build here rather than silently rendering nothing in light mode.
 *
 * `light-dark()` only accepts colours. Every token that differs by theme today
 * is a colour, and the build refuses a dark override whose light value is not
 * a literal colour, so a non-colour token cannot slip into a `light-dark()`
 * pair and invalidate itself.
 *
 * Run with `node build.mjs`, or `node build.mjs --watch` while editing.
 */
import { mkdirSync, readFileSync, watch, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = dirname(fileURLToPath(import.meta.url));
const SRC = join(ROOT, "src");
const DIST = join(ROOT, "dist");

const HEADER = (what) => `/*
 * @retrojb/tokens: ${what}
 *
 * GENERATED by packages/tokens/build.mjs. Do not edit; change the files in
 * packages/tokens/src instead.
 */
`;

/** A literal colour the contrast engine can parse, and `light-dark()` accepts. */
const LITERAL_COLOUR = /^(#[0-9a-f]{3,8}|(rgb|rgba|hsl|hsla)\(.*\))$/i;

/**
 * Custom property declarations in source order. Comments are stripped first,
 * since several of them quote declarations as examples.
 *
 * @param {string} css
 * @returns {Map<string, string>}
 */
function declarations(css) {
  const withoutComments = css.replace(/\/\*[\s\S]*?\*\//g, "");
  const found = new Map();
  for (const match of withoutComments.matchAll(
    /(--[a-z0-9-]+)\s*:\s*([^;]+);/gi,
  )) {
    found.set(match[1], match[2].trim());
  }
  return found;
}

/**
 * @param {Map<string, string>} decls
 * @param {string} indent
 */
function block(decls, indent = "    ") {
  return [...decls]
    .map(([name, value]) => `${indent}${name}: ${value};`)
    .join("\n");
}

/**
 * The density blocks, with a generated comfort block, after checking every
 * density declares exactly the space steps `base.css` does.
 *
 * @param {string} base
 */
function densityCss(base) {
  const source = readFileSync(join(SRC, "density.css"), "utf8");
  const comfort = new Map(
    [...declarations(base)].filter(([name]) => name.startsWith("--space-")),
  );
  const expected = [...comfort.keys()].join(",");

  for (const density of ["compact", "spacious"]) {
    const at = source.indexOf(`[data-density="${density}"]`);
    if (at === -1) throw new Error(`density.css has no ${density} block.`);
    const body = source.slice(at, source.indexOf("}", at));
    const names = [...declarations(body).keys()].join(",");
    if (names !== expected) {
      throw new Error(
        `density.css ${density} must declare ${expected}, in order. Found ${names}.`,
      );
    }
  }

  const comfortBlock = `
@layer theme {
  [data-density="comfort"] {
${block(comfort)}
  }
}
`;
  return source + comfortBlock;
}

function build() {
  const base = readFileSync(join(SRC, "base.css"), "utf8");
  const density = densityCss(base);
  const light = declarations(readFileSync(join(SRC, "light.css"), "utf8"));
  const dark = declarations(readFileSync(join(SRC, "dark.css"), "utf8"));

  const errors = [];
  for (const [name, value] of dark) {
    const lightValue = light.get(name);
    if (lightValue === undefined) {
      errors.push(`${name} is in dark.css but has no light value.`);
    } else if (
      !LITERAL_COLOUR.test(lightValue) ||
      !LITERAL_COLOUR.test(value)
    ) {
      errors.push(
        `${name} differs by theme but is not a literal colour in both files ` +
          `(light: ${lightValue}, dark: ${value}). light-dark() only accepts colours.`,
      );
    }
  }
  if (errors.length > 0) {
    throw new Error(`Token build failed:\n  ${errors.join("\n  ")}`);
  }

  /** @type {Map<string, string>} */
  const both = new Map();
  for (const [name, value] of light) {
    const darkValue = dark.get(name);
    both.set(name, darkValue ? `light-dark(${value}, ${darkValue})` : value);
  }

  const index = `${HEADER("both themes")}
/*
 * Theme selection. The OS setting by default; \`data-theme\` on \`<html>\` forces
 * one theme in either direction:
 *
 *   <html>                    follows the OS
 *   <html data-theme="light"> light, even on a dark OS
 *   <html data-theme="dark">  dark, even on a light OS
 *
 * \`color-scheme\` is what every \`light-dark()\` below reads, and it also themes
 * scrollbars and native form controls.
 */
@layer theme {
  :root {
    color-scheme: light dark;
  }

  :root[data-theme="light"] {
    color-scheme: light;
  }

  :root[data-theme="dark"] {
    color-scheme: dark;
  }
}

${base}
${density}
/* Colour: ramps and semantic tokens. Sources: src/light.css, src/dark.css. */
@layer theme {
  :root {
${block(both)}
  }
}
`;

  const pinned = (scheme, decls) => `${HEADER(`${scheme} theme only`)}
${base}
${density}
@layer theme {
  :root {
    color-scheme: ${scheme};

${block(decls)}
  }
}
`;

  mkdirSync(DIST, { recursive: true });
  writeFileSync(join(DIST, "index.css"), index);
  writeFileSync(join(DIST, "light.css"), pinned("light", light));
  writeFileSync(
    join(DIST, "dark.css"),
    pinned("dark", new Map([...light, ...dark])),
  );

  console.log(
    `tokens: ${light.size} colour tokens, ${dark.size} themed, written to dist/`,
  );
}

build();

if (process.argv.includes("--watch")) {
  console.log("tokens: watching src/");
  watch(SRC, () => {
    try {
      build();
    } catch (error) {
      console.error(error instanceof Error ? error.message : error);
    }
  });
}
